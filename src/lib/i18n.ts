/* ------------------------------------------------------------ dates -- */

const WEEKDAYS = {
  en: ["Sunday", "Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday"],
  es: ["domingo", "lunes", "martes", "miércoles", "jueves", "viernes", "sábado"],
};
const WEEKDAYS_SHORT = {
  en: ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"],
  es: ["dom", "lun", "mar", "mié", "jue", "vie", "sáb"],
};
const MONTHS = {
  en: ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"],
  es: ["ene", "feb", "mar", "abr", "may", "jun", "jul", "ago", "sep", "oct", "nov", "dic"],
};

/** The pieces of a calendar badge: "OCT", "7", "Wed". */
export function dateBadge(iso: string, lang: Lang): { month: string; day: number; weekday: string } {
  const d = new Date(`${iso}T00:00:00Z`);
  return {
    month: MONTHS[lang][d.getUTCMonth()],
    day: d.getUTCDate(),
    weekday: WEEKDAYS_SHORT[lang][d.getUTCDay()],
  };
}

/** "Tuesday, Oct 6" / "martes, 6 oct". */
export function longDate(iso: string, lang: Lang): string {
  const d = new Date(`${iso}T00:00:00Z`);
  return lang === "es"
    ? `${WEEKDAYS.es[d.getUTCDay()]}, ${d.getUTCDate()} ${MONTHS.es[d.getUTCMonth()]}`
    : `${WEEKDAYS.en[d.getUTCDay()]}, ${MONTHS.en[d.getUTCMonth()]} ${d.getUTCDate()}`;
}

/** 0 = Sunday … 6 = Saturday -> "Mon" / "lun". */
export function dayShort(weekday: number, lang: Lang): string {
  return WEEKDAYS_SHORT[lang][weekday];
}

/** "Mon – Thu" or just "Fri" for a run of days from summarizeWeek(). */
export function dayRange(from: number, to: number, lang: Lang): string {
  return from === to ? dayShort(from, lang) : `${dayShort(from, lang)} – ${dayShort(to, lang)}`;
}

/** "Tue, Oct 6" / "mar, 6 oct". */
export function shortDate(iso: string, lang: Lang): string {
  const d = new Date(`${iso}T00:00:00Z`);
  return lang === "es"
    ? `${WEEKDAYS_SHORT.es[d.getUTCDay()]}, ${d.getUTCDate()} ${MONTHS.es[d.getUTCMonth()]}`
    : `${WEEKDAYS_SHORT.en[d.getUTCDay()]}, ${MONTHS.en[d.getUTCMonth()]} ${d.getUTCDate()}`;
}

export function weekdayShort(iso: string, lang: Lang): string {
  return WEEKDAYS_SHORT[lang][new Date(`${iso}T00:00:00Z`).getUTCDay()];
}

export function monthDay(iso: string, lang: Lang): string {
  const d = new Date(`${iso}T00:00:00Z`);
  return lang === "es"
    ? `${d.getUTCDate()} ${MONTHS.es[d.getUTCMonth()]}`
    : `${MONTHS.en[d.getUTCMonth()]} ${d.getUTCDate()}`;
}

